function getTens(n: number): string {
  if (n < 20) return ones[n];
  if (n % 10 === 0) return tens[Math.floor(n / 10)];
  return higherTens[n as keyof typeof higherTens] || '';
}

export function numberToMarathiWords(num: number): string {
  if (num === 0) return 'शून्य';
  if (num < 0) return 'वजा ' + numberToMarathiWords(Math.abs(num));
  
  let words = '';
  
  if (Math.floor(num / 10000000) > 0) {
    words += getTens(Math.floor(num / 10000000)) + ' कोटी ';
    num %= 10000000;
  }
  
  if (Math.floor(num / 100000) > 0) {
    words += getTens(Math.floor(num / 100000)) + ' लाख ';
    num %= 100000;
  }
  
  if (Math.floor(num / 1000) > 0) {
    words += getTens(Math.floor(num / 1000)) + ' हजार ';
    num %= 1000;
  }
  
  if (Math.floor(num / 100) > 0) {
    const hundred = Math.floor(num / 100);
    if (hundred === 1) {
      words += 'शंभर ';
    } else {
      words += ones[hundred] + 'शे ';
    }
    num %= 100;
  }
  
  if (num > 0) {
    words += getTens(num) + ' ';
  }
  
  return words.trim() + ' रुपये मात्र';
}
